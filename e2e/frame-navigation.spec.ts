import { expect, test } from '@playwright/test'
import { albumLayer, FRAME, FRONT, openFeel, readView } from './feel-helpers.ts'
import { AUTOSAVE_QUIET_MS, drag, snapshotIdb, storedDoc, undoButton } from './helpers.ts'

test('search and map jumps keep the first view, including a repeat jump', async ({ page }) => {
  const start = { zoom: 0.78, panX: 10.5, panY: -7.25 }
  await openFeel(page, { viewport: start })
  const selected = albumLayer(page, 'picture')
  await selected.click()
  await page.keyboard.press('j')
  const search = page.getByRole('combobox', { name: 'Search frames' })
  await expect(search).toBeFocused()
  await search.fill(FRONT.name)
  await search.press('Enter')
  const returnButton = page.getByRole('button', { name: 'Return to start' })
  await expect(returnButton).toBeVisible()
  const front = await readView(page)
  expect(front).not.toEqual(start)
  await expect.poll(async () => (await storedDoc(page)).viewport).toEqual(front)
  const snapshot = await snapshotIdb(page)
  await page.getByRole('button', { name: 'Board map', exact: true }).click()
  const map = page.getByRole('region', { name: 'Board map' })
  await expect(map.getByTestId('board-map-viewport')).toBeVisible()
  await map.getByRole('button', { name: `Jump to ${FRONT.name}` }).click()
  await page.waitForTimeout(AUTOSAVE_QUIET_MS)
  expect(await snapshotIdb(page)).toEqual(snapshot)
  await map.getByRole('button', { name: `Jump to ${FRAME.name}` }).click()
  expect(await readView(page)).not.toEqual(front)
  await returnButton.click()
  expect(await readView(page)).toEqual(start)
  await expect.poll(async () => (await storedDoc(page)).viewport).toEqual(start)
  await expect(selected).toHaveAttribute('aria-selected', 'true')
  await expect(undoButton(page)).toBeDisabled()
})

test('Atlas focus consumes editor shortcuts and keeps paste inside its controls', async ({ page }) => {
  await openFeel(page)
  const selected = albumLayer(page, 'picture')
  await selected.click()
  const before = await snapshotIdb(page)
  await page.keyboard.press('j')
  const search = page.getByRole('combobox', { name: 'Search frames' })
  await expect(search).toBeFocused()
  await search.press('Shift+Tab')
  const jump = page.getByRole('button', { name: /Jump to…/ })
  await expect(jump).toBeFocused()
  await page.keyboard.press('Delete')
  await page.keyboard.press('Control+d')
  const received = await jump.evaluate((element) => {
    let bubbled = false
    const probe = () => { bubbled = true }
    window.addEventListener('paste', probe)
    const clipboardData = new DataTransfer()
    clipboardData.setData('text/plain', 'Front')
    element.dispatchEvent(new ClipboardEvent('paste', { bubbles: true, cancelable: true, clipboardData }))
    window.removeEventListener('paste', probe)
    return bubbled
  })
  expect(received).toBe(false)
  await page.keyboard.press('Escape')
  await expect(search).toHaveCount(0)
  await expect(selected).toHaveAttribute('aria-selected', 'true')
  await expect(undoButton(page)).toBeDisabled()
  expect(await snapshotIdb(page)).toEqual(before)
})

test('tour steps through detached previews and Escape leaves the exact board state', async ({ page }) => {
  await openFeel(page)
  const selected = albumLayer(page, 'picture')
  await selected.click()
  const before = await snapshotIdb(page)
  const view = await readView(page)
  const trigger = page.getByRole('button', { name: 'Frame tour', exact: true })
  await trigger.press('Enter')
  const tour = page.getByRole('dialog', { name: 'Frame tour' })
  await expect(tour.getByRole('img', { name: FRONT.name })).toBeVisible()
  await tour.getByRole('button', { name: 'Next frame' }).click()
  await expect(tour.getByRole('img', { name: FRAME.name })).toBeVisible()
  await page.keyboard.press('ArrowLeft')
  await expect(tour.getByRole('img', { name: FRONT.name })).toBeVisible()
  await page.keyboard.press('Delete')
  await page.keyboard.press('Control+d')
  await page.keyboard.press('Escape')
  await expect(tour).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await expect(selected).toHaveAttribute('aria-selected', 'true')
  expect(await readView(page)).toEqual(view)
  await expect(undoButton(page)).toBeDisabled()
  await page.waitForTimeout(AUTOSAVE_QUIET_MS)
  expect(await snapshotIdb(page)).toEqual(before)
})

test('a held drag blocks tour entry and can be cancelled before touring', async ({ page }) => {
  const at = await openFeel(page)
  const before = await snapshotIdb(page)
  const trigger = page.getByRole('button', { name: 'Frame tour', exact: true })
  const tour = page.getByRole('dialog', { name: 'Frame tour' })
  await drag(page, at(350, 280), at(390, 300), { hold: true })
  await trigger.evaluate((button: HTMLButtonElement) => button.click())
  await expect(tour).toHaveCount(0)
  await page.keyboard.press('Escape')
  await page.mouse.up()
  await trigger.press('Enter')
  await expect(tour).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(tour).toHaveCount(0)
  await expect(undoButton(page)).toBeDisabled()
  expect(await snapshotIdb(page)).toEqual(before)
})
