import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'
import { openApp, openBlank, seedRaw, snapshotIdb, storedDoc, undoButton, waitSaved } from './helpers.ts'

const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
const board = (page: Page) => page.locator('.workspace')
const appearance = async (page: Page) => JSON.parse((await snapshotIdb(page)).doc)?.appearance

test('edit appearance, reuse a saved preset, reset, and keep appearance through object undo and reload', async ({ page }) => {
  await page.goto('/')
  await expect(board(page)).toHaveAttribute('data-board-pattern', 'dots')
  await expect(board(page)).toHaveCSS('background-color', 'rgb(241, 243, 248)')
  await button(page, 'Appearance').click()
  const panel = page.getByRole('region', { name: 'Board appearance' })
  await panel.getByLabel('Background', { exact: true }).fill('#deeadf')
  await panel.getByRole('combobox', { name: 'Pattern', exact: true }).selectOption('grid')
  await panel.getByLabel('Pattern color', { exact: true }).fill('#919ea3')
  await expect(board(page)).toHaveAttribute('data-board-pattern', 'grid')
  await expect(board(page)).toHaveCSS('background-color', 'rgb(222, 234, 223)')
  await expect(board(page)).toHaveCSS('background-image', /linear-gradient/)
  const style = { background: '#deeadf', pattern: 'grid', patternColor: '#919ea3' }

  await panel.getByLabel('Preset name').fill('Mist')
  await button(page, 'Save preset').click()
  await button(page, 'Warm paper').click()
  await expect(board(page)).toHaveCSS('background-image', 'none')
  await button(page, 'Reset appearance').click()
  await expect(board(page)).toHaveAttribute('data-board-pattern', 'dots')
  await expect.poll(() => appearance(page)).toEqual({ presets: [{ name: 'Mist', style }] })
  await expect(undoButton(page)).toBeDisabled()
  expect((await storedDoc(page)).version).toBe(1)
  await button(page, 'Mist').click()
  await page.keyboard.press('Escape')
  await expect(panel).toHaveCount(0)
  await expect(button(page, 'Appearance')).toBeFocused()

  const previousSize = await board(page).evaluate((el) => getComputedStyle(el).backgroundSize)
  await page.keyboard.press('+')
  await expect(board(page)).not.toHaveCSS('background-size', previousSize)
  await page.keyboard.press('f')
  await page.mouse.click(210, 180)
  await expect.poll(async () => (await storedDoc(page)).frames?.length).toBe(1)
  await undoButton(page).click()
  await expect.poll(async () => (await storedDoc(page)).version).toBe(1)
  await expect.poll(() => appearance(page)).toEqual({ style, presets: [{ name: 'Mist', style }] })

  await waitSaved(page)
  await page.reload()
  await expect(board(page)).toHaveAttribute('data-board-pattern', 'grid')
  await expect(board(page)).toHaveCSS('background-color', 'rgb(222, 234, 223)')
  await button(page, 'Appearance').click()
  await expect(button(page, 'Mist')).toHaveAttribute('aria-pressed', 'true')
  await panel.getByLabel('Preset name').fill('mist')
  await expect(button(page, 'Save preset')).toBeDisabled()
  await button(page, 'Remove preset Mist').click()
  await expect.poll(() => appearance(page)).toEqual({ style })
  await button(page, 'Reset appearance').click()
  await waitSaved(page)
  await expect.poll(() => appearance(page)).toBeUndefined()
})

test('appearance uses the same conflict guard and preserves the newer board', async ({ page, context }) => {
  await openBlank(page)
  await seedRaw(page, 1, { version: 1, title: 'Two tabs', objects: [], viewport: { zoom: 1, panX: 0, panY: 0 } })
  await openApp(page)
  const other = await context.newPage()
  await openApp(other)
  await button(other, 'Appearance').click()
  await button(other, 'Blue grid').click()
  await waitSaved(other)
  const newer = await snapshotIdb(other)
  await other.close()

  await page.bringToFront()
  await button(page, 'Appearance').click()
  await button(page, 'Warm paper').click()
  await expect(page.getByTestId('readonly-banner')).toBeVisible()
  await expect(button(page, 'Appearance')).toBeDisabled()
  expect(await snapshotIdb(page)).toEqual(newer)
  await page.reload()
  await expect(board(page)).toHaveAttribute('data-board-pattern', 'grid')
})

test('opening Appearance commits the current text edit as its own undo step', async ({ page }) => {
  await page.goto('/')
  await expect(button(page, 'Appearance')).toBeEnabled()
  await page.keyboard.press('t')
  await page.mouse.click(250, 220)
  await expect(page.locator('textarea[data-fabric]')).toBeFocused()
  await page.keyboard.type('Album title')
  await button(page, 'Appearance').click()
  await expect(page.locator('textarea[data-fabric]')).toHaveCount(0)
  await button(page, 'Blue grid').click()
  await page.keyboard.press('Escape')
  await expect(page.locator('.inspector-title')).toHaveText('Text')
  await waitSaved(page)
  expect((await storedDoc(page)).objects[0]?.text).toBe('Album title')
  await undoButton(page).click()
  await expect.poll(async () => (await storedDoc(page)).objects).toEqual([])
  await expect(board(page)).toHaveAttribute('data-board-pattern', 'grid')
  await expect(undoButton(page)).toBeDisabled()
})
